#!/usr/bin/env python3
"""Generate the ergonomic C facade from the checked-in Diplomat C headers.

Unsupported ABI shapes fail generation rather than silently losing coverage.
The runtime adapter is handwritten; generated wrappers contain no business logic.
"""
import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
RECORDS = {
    ("Address", "new"): "FatooraAddressOptions",
    ("InvoiceBuilder", "new"): "FatooraInvoiceOptions",
    ("InvoiceBuilder", "add_line_item"): "FatooraLineItemOptions",
    ("InvoiceBuilder", "set_seller"): "FatooraPartyOptions",
    ("InvoiceBuilder", "set_buyer"): "FatooraPartyOptions",
    ("CsrProperties", "new"): "FatooraCsrOptions",
}


def snake(name):
    return re.sub(r"(?<!^)(?=[A-Z][a-z])|(?<=[a-z0-9])(?=[A-Z])", "_", name).lower()


def declaration(typ, name):
    """Format pointers conventionally: const Type *self, char **out."""
    return typ.replace("*", "").strip() + " " + "*" * typ.count("*") + name


def generate():
    headers = sorted((ROOT / "bindings/c/generated").glob("*.h"))
    texts = {p: p.read_text() for p in headers}
    opaque = sorted(set(re.findall(r"typedef struct (\w+) \1;", "\n".join(texts.values()))))
    handles = [t for t in opaque if t not in ("BindingError", "Text", "Xml")]

    def public_type(typ):
        for handle in handles:
            typ = re.sub(r"\b" + handle + r"\b", "Fatoora" + handle, typ)
        return typ.replace("InvoiceOutcome", "FatooraInvoiceOutcome")

    public = ["""/* Generated by scripts/generate_c_facade.py. Do not edit. */
#ifndef FATOORA_H
#define FATOORA_H
#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>
#ifdef __cplusplus
extern "C" {
#endif

/* Status preserves native error codes, including future unknown codes. */
typedef int32_t FatooraStatus;
enum {
    FATOORA_OK = 0, FATOORA_INVALID_INPUT = 1, FATOORA_VALIDATION = 2,
    FATOORA_PARSE = 3, FATOORA_XML = 4, FATOORA_CRYPTO = 5, FATOORA_IO = 6,
    FATOORA_NETWORK = 7, FATOORA_UNAUTHORIZED = 8, FATOORA_INTERNAL = 9,
    FATOORA_API = 10
};
enum { FATOORA_NON_PRODUCTION = 0, FATOORA_SIMULATION = 1, FATOORA_PRODUCTION = 2 };
enum { FATOORA_TAX = 0, FATOORA_PREPAYMENT = 1, FATOORA_CREDIT_NOTE = 2, FATOORA_DEBIT_NOTE = 3 };
enum { FATOORA_STANDARD = 0, FATOORA_SIMPLIFIED = 1 };
enum { FATOORA_VAT_EXEMPT = 0, FATOORA_VAT_STANDARD = 1, FATOORA_VAT_ZERO = 2, FATOORA_VAT_OUT_OF_SCOPE = 3 };
enum { FATOORA_FLAG_THIRD_PARTY = 1, FATOORA_FLAG_NOMINAL = 2, FATOORA_FLAG_EXPORT = 4,
       FATOORA_FLAG_SUMMARY = 8, FATOORA_FLAG_SELF_BILLED = 16 };
typedef enum FatooraInvoiceOutcome {
    FATOORA_OUTCOME_UNKNOWN = 0, FATOORA_OUTCOME_ACCEPTED = 1, FATOORA_OUTCOME_REJECTED = 2
} FatooraInvoiceOutcome;
typedef struct FatooraBytesView { const uint8_t *data; size_t len; } FatooraBytesView;
typedef struct FatooraError FatooraError;
void fatoora_string_free(char *value);
void fatoora_error_free(FatooraError *error);
FatooraStatus fatoora_error_code(const FatooraError *error);
const char *fatoora_error_message(const FatooraError *error);
const char *fatoora_error_details_json(const FatooraError *error);

/* UTF-8 inputs are NUL-terminated. Nullable inputs represent optional values.
 * Decimal inputs/outputs are exact decimal strings. All output pointers are
 * required; error is optional. Outputs are cleared on entry, including failure.
 * Free previous outputs/errors before reusing their slots. Strings and handle
 * outputs are owned; NULL optional output means absence, not an empty string.
 * Byte views borrow their immutable owner. Free functions accept NULL.
 * build/sign/into_xml consume inner state; the outer handle still needs free.
 * See docs/development/c-api.md for consumption and synchronization rules. */
"""]
    public.extend(f"typedef struct {t} Fatoora{t};" for t in handles)
    records_index = len(public)
    records = {}
    implementation = ["/* Generated by scripts/generate_c_facade.py. Do not edit. */", '#include "fatoora.h"', "#include <stdlib.h>", "#include <string.h>"]
    implementation.extend(f'#include "generated/{p.name}"' for p in headers if not p.name.endswith(".d.h") and p.name != "diplomat_runtime.h")
    implementation.append((ROOT / "scripts/c_facade_runtime.c").read_text())
    count = 0
    for path, text in texts.items():
        results = dict(re.findall(r"typedef struct (fatoora_\w+_result) \{union \{(.*?)\}; bool is_ok;\} \1;", text))
        declarations = re.findall(r"^.*\bfatoora_\w+\(.*\);$", text, re.M)
        for declaration_text in declarations:
            match = re.fullmatch(r"(\w+\*?) (fatoora_(\w+?)_(\w+))\((.*?)\);", declaration_text)
            if not match:
                raise ValueError(f"Unsupported function declaration: {declaration_text}")
            ret, native, owner, method, params = match.groups()
            if owner in ("BindingError", "Text") or (owner == "Xml" and method == "destroy"):
                continue
            name = "fatoora_" + snake(owner) + "_" + ("free" if method == "destroy" else method)
            args, call, checks, init = [], [], [], ["    if (error) *error = NULL;"]
            writer = False
            for param in ([] if params == "void" else params.split(", ")):
                match = re.fullmatch(r"(.+?)(\w+)", param)
                if not match:
                    raise ValueError(f"Unsupported parameter: {param}")
                typ, arg = match.groups()
                typ = typ.strip()
                if typ == "DiplomatWrite*":
                    writer = True
                    call.append("&write")
                elif typ in ("DiplomatStringView", "OptionStringView"):
                    args.append(f"const char *{arg}")
                    if typ == "DiplomatStringView":
                        checks.append(f"!{arg}")
                    call.append(f"fatoora_private_{'string' if typ == 'DiplomatStringView' else 'optional'}({arg})")
                elif typ == "DiplomatU8View":
                    args.extend([f"const uint8_t *{arg}", f"size_t {arg}_len"])
                    checks.append(f"((!{arg} && {arg}_len) || {arg}_len > PTRDIFF_MAX)")
                    # Rust slices require a non-null pointer even for zero bytes.
                    call.append(f"(DiplomatU8View){{{arg} ? {arg} : (const uint8_t *)\"\", {arg}_len}}")
                else:
                    if typ not in {"uint8_t", "uint16_t", "uint64_t", "size_t", "bool"} and typ not in {
                        pointer for handle in handles for pointer in (handle + "*", "const " + handle + "*")
                    }:
                        raise ValueError(f"Unsupported parameter type in {native}: {typ}")
                    if typ == "uint8_t":
                        args.append(f"int32_t {arg}")
                        checks.append(f"({arg} < 0 || {arg} > UINT8_MAX)")
                        call.append(f"(uint8_t){arg}")
                    else:
                        args.append(declaration(public_type(typ), arg))
                        if "*" in typ and method != "destroy":
                            checks.append(f"!{arg}")
                        call.append(arg)
            expression = f"{native}({', '.join(call)})"
            record = RECORDS.get((owner, method))
            bindings = []
            if record:
                has_self = params.startswith(owner + "* self")
                fields = args[1:] if has_self else args[:]
                if record in records and records[record] != fields:
                    raise ValueError(f"Conflicting record: {record}")
                records[record] = fields
                for field in fields:
                    field_name = field.rsplit(" ", 1)[-1].lstrip("*")
                    bindings.append(f"    {field} = options->{field_name};")
                args = (args[:1] if has_self else []) + [f"const {record} *options"]
            if method == "destroy":
                signature = f"void {name}({', '.join(args)})"
                body = [f"    if (self) {expression};"]
            else:
                fields = results.get(ret)
                if ret.endswith("_result") and fields is None:
                    raise ValueError(f"Unsupported result layout: {native}")
                fallible = fields is not None and "BindingError* err;" in fields
                ok = re.search(r"(\w+\*?) ok;", fields or "")
                value_type = ok.group(1) if ok else (ret if fields is None else None)
                if value_type and value_type not in {
                    "Text*", "bool", "uint8_t", "uint16_t", "uint64_t", "size_t",
                    "InvoiceOutcome", "DiplomatU8View", *(handle + "*" for handle in handles)
                }:
                    raise ValueError(f"Unsupported return type in {native}: {value_type}")
                if writer:
                    if value_type:
                        raise ValueError(f"Unexpected writer value: {native}")
                    out_type = "char*"
                elif value_type == "Text*":
                    out_type = "char*"
                elif value_type == "DiplomatU8View":
                    out_type = "FatooraBytesView"
                elif value_type:
                    out_type = public_type(value_type)
                else:
                    out_type = None
                if out_type:
                    args.append(declaration(out_type + "*", "out"))
                    checks.append("!out")
                    zero = "(FatooraBytesView){0}" if out_type == "FatooraBytesView" else "0"
                    init.append(f"    if (out) *out = {zero};")
                optional_scalar = fields is not None and not fallible
                if optional_scalar:
                    args.append("bool *has_value")
                    checks.append("!has_value")
                    init.append("    if (has_value) *has_value = false;")
                args.append("FatooraError **error")
                signature = f"FatooraStatus {name}({', '.join(args)})"
                body = init[:]
                if record:
                    body.extend(["    if (!options)", '        return fatoora_private_fail(FATOORA_INVALID_INPUT, "options is NULL", error);', *bindings])
                if checks:
                    body.extend([f"    if ({' || '.join(checks)})", '        return fatoora_private_fail(FATOORA_INVALID_INPUT, "required argument is NULL or integer is out of range", error);'])
                if writer:
                    body.extend(["    DiplomatWrite write = fatoora_private_writer();", "    if (write.grow_failed)", '        return fatoora_private_fail(FATOORA_INTERNAL, "output allocation failed", error);'])
                if fallible:
                    body.extend([f"    {ret} result = {expression};", "    if (!result.is_ok) {"])
                    if writer:
                        body.append("        free(write.buf);")
                    body.extend(["        return fatoora_private_error(result.err, error);", "    }"])
                    value = "result.ok" if value_type else None
                elif optional_scalar:
                    body.extend([f"    {ret} result = {expression};", "    *has_value = result.is_ok;", "    if (result.is_ok) *out = result.ok;"])
                    value = None
                elif value_type:
                    body.append(f"    {value_type} value = {expression};")
                    value = "value"
                else:
                    body.append(f"    {expression};")
                    value = None
                if writer:
                    body.append("    return fatoora_private_finish(&write, out, error);")
                elif value_type == "Text*":
                    body.append(f"    return fatoora_private_text({value}, out, error);")
                else:
                    if value and value_type == "DiplomatU8View":
                        body.extend([f"    out->data = {value}.data;", f"    out->len = {value}.len;"])
                    elif value:
                        cast = "(FatooraInvoiceOutcome)" if value_type == "InvoiceOutcome" else ""
                        body.append(f"    *out = {cast}{value};")
                    body.append("    return FATOORA_OK;")
            # Keep declarations readable without requiring a formatter.
            public.append(signature.replace(", ", ",\n    ") + ";")
            implementation.append(signature + " {\n" + "\n".join(body) + "\n}")
            count += 1
    record_declarations = [f"typedef struct {name} {{\n" + "\n".join(f"    {field};" for field in fields) + f"\n}} {name};\n" for name, fields in records.items()]
    public[records_index:records_index] = record_declarations
    public.append('#ifdef __cplusplus\n}\n#endif\n#endif /* FATOORA_H */')
    return {"fatoora.h": "\n".join(public) + "\n", "fatoora.c": "\n\n".join(implementation) + "\n"}, count


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    files, count = generate()
    directory = ROOT / "bindings/c"
    directory.mkdir(parents=True, exist_ok=True)
    for name, content in files.items():
        path = directory / name
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f"Stale C facade: {path.relative_to(ROOT)}")
        else:
            path.write_text(content)
    print(f"{'Checked' if args.check else 'Generated'} {count} C facade operations")


if __name__ == "__main__":
    main()
