#!/usr/bin/env python3
"""Generate the JavaScript facade tables and declarations from the Diplomat output.

``bindings/js/patch.mjs`` adapts the generated classes in place, so the package
root and ``fatoority/raw`` share one shape. This script derives that shape from
``bindings/js/generated/*.d.mts`` and writes:

* ``bindings/js/members.mjs``: the runtime tables patch.mjs applies;
* ``bindings/js/raw.d.mts``: declarations of the adapted classes, which the
  package root re-exports and partly replaces in ``index.d.mts``.

The shape matches the Kotlin and .NET facades:

* value getters (zero-argument instance methods returning a string, number,
  bigint, boolean or enum, optional or not, on classes and enums) become
  read-only properties;
  methods returning native owners stay methods, as do ``to*``/``as*``/``into*``
  conversions, ``with*`` copies, ``build*``, ``ensure*``, ``len`` and ``isEmpty``;
* a fallible ``x(): string`` getter with an ``xPresent(): boolean`` sibling
  (the FFI's ``x_present``/``x`` pair, see docs/development/diplomat.md) is
  one ``string | null`` property; patch.mjs removes ``xPresent``;
* the Rust ``new`` constructor is ``create``; patch.mjs removes ``new_``;
* binary data is a ``Uint8Array``: the ``&[u8]`` getter ``Bytes::as_slice``
  (Diplomat's ``asSlice(): Array<number>``) is ``toUint8Array()``, returning
  an independent copy, and ``&[u8]`` parameters accept a ``Uint8Array`` or an
  array of byte values.

Decimal amounts stay decimal strings: JavaScript has no decimal type and
``number`` would round money.
"""
import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
JS = ROOT / "bindings/js"
GENERATED = JS / "generated"
HEADER = "// Generated by scripts/generate_js_facade.py; do not edit.\n"

# Generated classes passed through unchanged: `BindingError` is the `cause`
# of every FatooraError.
UNCHANGED = {"BindingError"}
VERB_PREFIXES = ("to", "as", "into", "with", "build", "ensure")
VERBS = {"len", "isEmpty"}
SCALARS = {"string", "number", "bigint", "boolean"}
# Diplomat declares every `&[u8]` as `Array<number>`; the FFI has no other slices.
BYTE_SLICE = "Array<number>"
BYTE_INPUT = "Uint8Array | readonly number[]"
# `&[u8]` results renamed to a method returning a `Uint8Array` copy.
BYTE_RESULTS = {"Bytes": {"asSlice": "toUint8Array"}}
BYTE_RESULT_DOC = "  /** Copy the bytes into a new `Uint8Array`, independent of this object. */\n"
MEMBER = re.compile(r"^    (?P<static>static )?(?P<name>\w+)\((?P<params>[^)]*)\): (?P<ret>[^;]+);$")


def parse(path):
    """Return (class doc, [(doc, static, name, params, ret)]) for an opaque class."""
    text = path.read_text()
    match = re.search(r"^((?:/\*\*.*?\*/\n)?)export class (\w+) \{\n(.*)^\}", text, re.M | re.S)
    if not match or "get ffiValue(): pointer;" not in match.group(3):
        return None
    members, doc = [], []
    for line in match.group(3).splitlines():
        if line.strip().startswith("/**") or doc and not doc[-1].strip().endswith("*/"):
            doc.append(line)
            continue
        member = MEMBER.match(line)
        if member and member["name"] != "constructor":
            members.append(("\n".join(doc), bool(member["static"]), member["name"],
                            member["params"], member["ret"]))
        if line.strip():
            doc = []
    return match.group(1), members


def is_property(name, static, params, ret, enums):
    return (not static and not params and name not in VERBS
            and name not in VERB_PREFIXES
            and not re.match(rf"(?:{'|'.join(VERB_PREFIXES)})[A-Z]", name)
            and ret.removesuffix(" | null") in SCALARS | enums)


def facade():
    enums, classes, properties = set(), {}, {}
    for path in sorted(GENERATED.glob("*.d.mts")):
        name = path.name.removesuffix(".d.mts")
        if name in ("index", "diplomat-runtime"):
            continue
        parsed = parse(path)
        if parsed is None:
            enums.add(name)
        elif name not in UNCHANGED:
            classes[name] = parsed
    # Enums pass through unless they have value methods (`InvoiceFlag.bit()`),
    # which become properties as on the classes.
    enum_declarations = {}
    for name in sorted(enums):
        text = (GENERATED / f"{name}.d.mts").read_text()
        match = re.search(r"^((?:/\*\*.*?\*/\n)?)export class (\w+) \{\n(.*)^\}", text, re.M | re.S)
        body = match.group(3)
        for member in [m for m in map(MEMBER.match, body.splitlines()) if m]:
            if is_property(member["name"], bool(member["static"]), member["params"], member["ret"], enums):
                properties.setdefault(name, []).append(member["name"])
                body = body.replace(member.group(0), f"    get {member['name']}(): {member['ret']};")
        if name in properties:
            lines = re.sub(r"\n{3,}", "\n\n", body).strip("\n").splitlines()
            body = "\n".join(line[2:] if line.startswith("    ") else line for line in lines)
            enum_declarations[name] = f"{match.group(1)}export declare class {name} {{\n{body}\n}}"
    for path in sorted(GENERATED.glob("*.mjs")):
        for rust_type in re.findall(r'DiplomatBuf\.slice\(wasm, \w+, "(\w+)"\)', path.read_text()):
            if rust_type != "u8":
                raise SystemExit(f"{path.name}: unexpected {rust_type} slice parameter")
    optionals, declarations = {}, []
    for name, (class_doc, members) in classes.items():
        body = ["  private constructor();"]
        getters = {m: r for _, static, m, params, r in members if not static and not params}
        pairs = {m: m + "Present" for m, r in getters.items()
                 if r == "string" and getters.get(m + "Present") == "boolean"}
        if pairs:
            optionals[name] = pairs
        for doc, static, method, params, ret in members:
            if method in ("new_",) and not static:
                raise SystemExit(f"{name}.{method}: unexpected instance constructor")
            if method in pairs.values():
                continue
            shown = ret + " | null" if method in pairs else ret
            prefix = "  " + doc.replace("\n    ", "\n  ").strip() + "\n" if doc else ""
            params = params.replace(BYTE_SLICE, BYTE_INPUT)
            if ret == BYTE_SLICE:
                renamed = BYTE_RESULTS.get(name, {}).get(method)
                if renamed is None or static or params:
                    raise SystemExit(f"{name}.{method}: add the byte slice result to BYTE_RESULTS")
                body.append(f"{BYTE_RESULT_DOC}  {renamed}(): Uint8Array;")
            elif is_property(method, static, params, ret, enums):
                properties.setdefault(name, []).append(method)
                body.append(f"{prefix}  get {method}(): {shown};")
            elif static and method == "new_":
                body.append(f"{prefix}  static create({params}): {shown};")
            else:
                body.append(f"{prefix}  {'static ' if static else ''}{method}({params}): {shown};")
        declarations.append(f"{class_doc}export declare class {name} {{\n" + "\n".join(body) + "\n}")

    def table(entries):
        return "{\n" + "".join(
            f"  {name}: [{', '.join(repr(m) for m in members)}],\n"
            for name, members in sorted(entries.items())) + "}"

    def pairs_table(entries):
        return "{\n" + "".join(
            f"  {name}: {{ {', '.join(f'{m}: {h!r}' for m, h in sorted(pairs.items()))} }},\n"
            for name, pairs in sorted(entries.items())) + "}"

    members_mjs = (
        HEADER
        + "// Read by patch.mjs; see scripts/generate_js_facade.py for the rules.\n\n"
        + "/** Zero-argument value getters exposed as read-only properties. */\n"
        + f"export const properties = {table(properties)};\n\n"
        + "/**\n"
        + " * Fallible string getters that are null when their `*Present` sibling is false.\n"
        + " * patch.mjs merges each pair into one member and removes the `*Present` method.\n"
        + " */\n"
        + f"export const optionalResults = {pairs_table(optionals)};\n\n"
        + "/** `&[u8]` results by generated name: the public name returns a `Uint8Array` copy. */\n"
        + f"export const byteResults = {pairs_table(BYTE_RESULTS)};\n"
    )
    exported = sorted(enums - set(enum_declarations)) + sorted(UNCHANGED)
    raw_dts = (
        HEADER
        + "// The generated classes as adapted by patch.mjs: value getters are properties,\n"
        + "// optional strings are `string | null` and failures throw the classes from errors.mjs.\n"
        + "import type { " + ", ".join(sorted(enums - set(enum_declarations)))
        + " } from './generated/index.mjs';\n"
        + "export { codepoint } from './generated/index.mjs';\n"
        + "export { " + ", ".join(exported) + " } from './generated/index.mjs';\n\n"
        + "\n\n".join(list(enum_declarations.values()) + declarations) + "\n"
    )
    return {JS / "members.mjs": members_mjs, JS / "raw.d.mts": raw_dts}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if the checked-in files differ")
    args = parser.parse_args()
    for path, content in facade().items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f"Stale JavaScript facade: {path.relative_to(ROOT)}; run scripts/generate_bindings.py")
        else:
            path.write_text(content)


if __name__ == "__main__":
    main()
